#!/usr/bin/env node
/**
 * Generates the local development credentials for the NaijaDeals infra stack.
 *
 *   node deploy/dev-infra/gen-secrets.mjs
 *
 * Idempotent: existing files are never overwritten, so restarting the stack or
 * re-running this script cannot rotate a password behind a running container.
 * Values are written to disk only — never printed to stdout, never logged.
 */
import { randomBytes } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const runtimeDir = join(here, ".runtime");
const envPath = join(here, ".env");
const rootEnvPath = join(here, "..", "..", ".env");

const token = (bytes = 32) => randomBytes(bytes).toString("base64url");
const created = [];

mkdirSync(runtimeDir, { recursive: true });

function writeOnce(path, body, mode = 0o600) {
  if (existsSync(path)) return false;
  writeFileSync(path, body, { mode });
  created.push(path.replace(here, "."));
  return true;
}

/* ------------------------------------------------------------------ .env --- */
if (!existsSync(envPath)) {
  const env = [
    "# Generated by gen-secrets.mjs. Development only. Never commit this file.",
    `VALKEY_PASSWORD=${token(24)}`,
    `MEILI_MASTER_KEY=${token(32)}`,
    `PGVECTOR_PASSWORD=${token(24)}`,
    "GRAFANA_ADMIN_USER=admin",
    `GRAFANA_ADMIN_PASSWORD=${token(18)}`,
    ""
  ].join("\n");
  writeOnce(envPath, env);
}

const env = Object.fromEntries(
  readFileSync(envPath, "utf8")
    .split(/\r?\n/)
    .filter((line) => line && !line.startsWith("#") && line.includes("="))
    .map((line) => {
      const at = line.indexOf("=");
      return [line.slice(0, at).trim(), line.slice(at + 1).trim()];
    })
);

/* --------------------------------------------------- valkey config file --- */
writeOnce(
  join(runtimeDir, "valkey.conf"),
  [
    "# Generated. Development only.",
    "bind 0.0.0.0",
    "protected-mode no",
    `requirepass ${env.VALKEY_PASSWORD}`,
    "port 6379",
    "appendonly yes",
    "appendfsync everysec",
    "save 900 1",
    // A queue backend must never evict jobs under memory pressure.
    "maxmemory 768mb",
    "maxmemory-policy noeviction",
    "enable-debug-command no",
    ""
  ].join("\n")
);

/* ------------------------------------------------ metrics scrape token --- */
// Prometheus reads this file; the app requires it as a bearer token so
// /api/metrics is never anonymous, even in development.
writeOnce(join(runtimeDir, "metrics-token"), `${token(24)}\n`);

/* ------------------------------------------------------ SeaweedFS S3 IAM --- */if (!existsSync(join(runtimeDir, "s3.json"))) {
  const accessKey = `NDDEV${randomBytes(8).toString("hex").toUpperCase()}`;
  const secretKey = token(30);
  const bucket = "naijadeals-dev";
  const scoped = ["Read", "Write", "List", "Tagging", "Admin"].map((action) => `${action}:${bucket}`);
  writeOnce(
    join(runtimeDir, "s3.json"),
    `${JSON.stringify({ identities: [{ name: "nd-dev", credentials: [{ accessKey, secretKey }], actions: [...scoped, "CreateBucket"] }] }, null, 2)}\n`
  );
}

/* ------------------------------------------- application-side variables --- */
const s3 = JSON.parse(readFileSync(join(runtimeDir, "s3.json"), "utf8"));
const s3Creds = s3.identities[0].credentials[0];

const appVars = {
  VALKEY_URL: `redis://:${env.VALKEY_PASSWORD}@127.0.0.1:6380/0`,
  MEILISEARCH_URL: "http://127.0.0.1:7700",
  MEILISEARCH_API_KEY: env.MEILI_MASTER_KEY,
  S3_ENDPOINT: "http://127.0.0.1:9002",
  S3_REGION: "us-east-1",
  S3_BUCKET: "naijadeals-dev",
  S3_ACCESS_KEY_ID: s3Creds.accessKey,
  S3_SECRET_ACCESS_KEY: s3Creds.secretKey,
  S3_FORCE_PATH_STYLE: "true",
  VECTOR_DATABASE_URL: `postgresql://nd_vector:${env.PGVECTOR_PASSWORD}@127.0.0.1:5433/naijadeals_vectors`,
  PROMETHEUS_URL: "http://127.0.0.1:9091",
  GRAFANA_URL: "http://127.0.0.1:3002",
  OSRM_URL: "http://127.0.0.1:5000",
  METRICS_TOKEN: readFileSync(join(runtimeDir, "metrics-token"), "utf8").trim(),
  BACKUP_ENCRYPTION_KEY: token(32)
};

if (existsSync(rootEnvPath)) {
  const current = readFileSync(rootEnvPath, "utf8");
  const present = new Set(
    current
      .split(/\r?\n/)
      .map((line) => line.split("=")[0]?.trim())
      .filter(Boolean)
  );
  const missing = Object.entries(appVars).filter(([key]) => !present.has(key));
  if (missing.length) {
    const block = [
      "",
      "# Local development infrastructure (generated by deploy/dev-infra/gen-secrets.mjs).",
      "# Development values only; regenerate with a fresh stack instead of reusing in production.",
      ...missing.map(([key, value]) => `${key}="${value}"`),
      ""
    ].join("\n");
    writeFileSync(rootEnvPath, current.replace(/\s*$/, "\n") + block, { mode: 0o600 });
    created.push("../../.env (appended " + missing.length + " infra keys)");
  }
} else {
  process.stderr.write("No root .env found; skipped application variables.\n");
}

process.stdout.write(
  created.length
    ? `Created: ${created.join(", ")}\n(Values are on disk only and were not printed.)\n`
    : "Nothing to create; all secrets already exist.\n"
);
